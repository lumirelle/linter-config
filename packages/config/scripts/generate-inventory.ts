import type { OxlintRule } from '../src/oxlint/inventory'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { readOxlintRules } from './oxlint-rules'

/**
 * Writes the committed Oxlint rule inventory from the installed Oxlint.
 *
 * Run it with `mise run //packages/config:inventory`; the drift test fails until the committed
 * inventory matches the installed binary, so an Oxlint upgrade that renames or drops a rule is a
 * deliberate regeneration rather than a silent change in what the Oxlint Emission can emit.
 */
const TARGET = fileURLToPath(new URL('../src/oxlint/inventory.generated.ts', import.meta.url))

const { version, rules } = readOxlintRules()

writeFileSync(TARGET, render(version, rules))

function render(version: string, rules: OxlintRule[]): string {
  const rows = rules
    .map(({ scope, rule, typeAware }) => `  ['${scope}', '${rule}', ${typeAware}],`)
    .join('\n')

  return `// Generated by \`mise run //packages/config:inventory\` from oxlint ${version}. Do not edit by hand:
// a rule rename or removal must be a deliberate regeneration, reviewable as a diff.
import type { OxlintRuleRow } from './inventory'

/** The Oxlint version the committed inventory was generated from. */
export const OXLINT_VERSION = '${version}'

/** Every rule that Oxlint emits, as \`[scope, rule, typeAware]\`, sorted by scope, then rule. */
export const OXLINT_RULES: readonly OxlintRuleRow[] = [
${rows}
]
`
}
