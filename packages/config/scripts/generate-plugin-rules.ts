import type { RuleEntry } from '../src/types'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import e18ePlugin from '@e18e/eslint-plugin'
import { configs as regexpConfigs } from 'eslint-plugin-regexp'

/**
 * Writes the rule tables the Source Modules need from two `jsPlugins`-backed plugin packages.
 *
 * Run it with `mise run //packages/config:plugin-rules`. Source imports no plugin package, so the
 * sets Upstream takes from a plugin's own `configs` (`eslint-plugin-regexp`'s `flat/recommended`
 * and `@e18e/eslint-plugin`'s three named sets) are generated here once and committed; a plugin
 * upgrade that changes them is then a reviewable diff instead of a silent rule change.
 */
const TARGET = fileURLToPath(new URL('../src/modules/plugin-rules.generated.ts', import.meta.url))

/** One committed table: a const name, the plugin set it comes from, and its rules. */
interface Table {
  name: string
  source: string
  rules: Record<string, RuleEntry>
}

const e18eConfigs = e18ePlugin.configs as unknown as Record<string, { rules?: Record<string, RuleEntry> }>

const tables: Table[] = [
  {
    name: 'REGEXP_RECOMMENDED_RULES',
    source: 'eslint-plugin-regexp `configs[\'flat/recommended\']`',
    rules: (regexpConfigs['flat/recommended'] as { rules: Record<string, RuleEntry> }).rules,
  },
  ...['modernization', 'moduleReplacements', 'performanceImprovements'].map(id => ({
    name: `E18E_${id.replace(/([A-Z])/gu, '_$1').toUpperCase()}_RULES`,
    source: `@e18e/eslint-plugin \`configs.${id}\``,
    rules: e18eConfigs[id]?.rules ?? {},
  })),
]

/** The house style is single quotes, and every rule entry of these sets is a bare severity. */
function quote(key: string): string {
  return `'${key}'`
}

function renderEntry([key, entry]: [string, RuleEntry]): string {
  if (typeof entry !== 'string') {
    throw new Error(`"${key}" is not a bare severity; teach the generator how to write "${JSON.stringify(entry)}".`)
  }
  return `  ${quote(key)}: ${quote(entry)},`
}

function render(table: Table): string {
  const entries = Object.entries(table.rules)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(renderEntry)
  // A line comment, not JSDoc: the plugin's package name would read as a JSDoc tag.
  return `// ${table.source}.\nexport const ${table.name}: Readonly<Partial<Record<RuleKey, RuleEntry>>> = {\n${entries.join('\n')}\n}\n`
}

const header = [
  '// Generated by `mise run //packages/config:plugin-rules` from eslint-plugin-regexp and',
  '// @e18e/eslint-plugin. Do not edit by hand: every table is the plugin\'s own `configs` output,',
  '// committed because Source imports no plugin package.',
  'import type { RuleEntry, RuleKey } from \'../types\'',
  '',
].join('\n')

writeFileSync(TARGET, `${header}${tables.map(render).join('\n')}`)
